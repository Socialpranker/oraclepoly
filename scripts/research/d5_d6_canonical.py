#!/usr/bin/env python3
"""D5 + D6 + D6b — Canonical RA on /mnt/data/canonical/.

D5 LongHorizonExtremeFade: NO-fade на entry_yes >= 0.70, horizon >= 3 days
D6 RetailBullishOvershoot: D5 + maker_direction_ratio (proxy buy/sell pressure)
D6b: same as D6 but 5-day horizon focus (vs D6 12h)

Filters:
  - entry_yes 0.70-0.95 (extreme excluded)
  - horizon >= 3 days
  - exclude Other, Minute Markets

Output: 3 md files в docs/backtests/.
"""

from __future__ import annotations

import time
from pathlib import Path

import duckdb

from _backtest_params import DEFAULT_FEE_PCT, SLIPPAGE_PP as _SLIP, BACKTEST_DAYS

MARKETS = "/mnt/data/canonical/markets_clean.parquet"
SNAPS = "/mnt/data/canonical/price_snapshots.parquet"
TRADES = "/mnt/data/canonical/trade_buckets.parquet"

EXCLUDE_CATS = ["Other", "Minute Markets"]

SLIPPAGE_PP = _SLIP["D5"]


def horizon_band(days):
    if days < 3:
        return None
    if days < 7:
        return "3-7d"
    if days < 14:
        return "7-14d"
    return "14d+"


def zone(price):
    if 0.70 <= price < 0.85:
        return "high"
    if 0.85 <= price < 0.95:
        return "extreme"
    return None


def write_md(detector, verdict, n, days, gross_roi, net_roi, wr, daily_pnl, haircut, buckets, hypothesis, filters_text, extra=""):
    out = Path(f"docs/backtests/{detector}.md")
    out.parent.mkdir(parents=True, exist_ok=True)

    md = f"""---
detector: {detector}
verdict: {verdict}
backtest_date: 2026-05-03
canonical_source: scripts/research/d5_d6_canonical.py
data_source: /mnt/data/canonical/markets_clean.parquet + price_snapshots.parquet
n_signals: {n}
backtest_days: {days}
roi_net_pct: {round(net_roi, 1)}
wr_pct: {round(wr, 1)}
daily_realistic_usd_at_5k: {round(daily_pnl, 2)}
daily_realistic_usd_at_1k: {round(daily_pnl / 5, 2)}
honest_haircut_factor: {haircut}
honest_daily_usd_at_5k: {round(daily_pnl * haircut, 2)}
honest_daily_usd_at_1k: {round(daily_pnl * haircut / 5, 2)}
honest_haircut_reason: net of fees ({DEFAULT_FEE_PCT}% × 2) + slippage ({SLIPPAGE_PP}pp). D5/D6 overlap with D7b extended zone.
trades_per_day: {round(n / days, 2)}
adversarial_mirror_pass: false
adversarial_mirror_note: NO-only edge на extreme/high zones, asymmetric (favorite-longshot bias)
post_v2_split: {verdict.lower()}
---

# {detector} — Canonical Backtest

**Hypothesis:** {hypothesis}

**Verdict:** {verdict}

## BUCKET_WR table (canonical {days} days)

| horizon | zone    | n     | WR    | avg_no_cost |
|---------|---------|-------|-------|-------------|
"""
    for b in buckets:
        md += f"| {b['horizon']:<7} | {b['zone']:<7} | {b['n']:>5} | {b['wr']:>4.1f}% | {b['avg_cost']:>11.4f} |\n"

    md += f"""
## Filters

{filters_text}

## Honest expectations vs canonical

- **Canonical gross ROI:** {gross_roi:+.1f}% (n={n} signals)
- **Net ROI:** {net_roi:+.1f}% (after fees + {SLIPPAGE_PP}pp slip)
- **Daily PnL @ $5K (raw):** ${daily_pnl:+.2f}
- **Honest haircut:** ×{haircut} → ${daily_pnl * haircut:+.2f}/day
- **Trades/day:** {n / days:.2f}

{extra}

Generated by `scripts/research/d5_d6_canonical.py` on canonical parquet.
"""
    out.write_text(md)
    print(f"  → {out}")


def main():
    print("=" * 70)
    print("D5/D6/D6b — Canonical RA on /mnt/data/canonical/")
    print("=" * 70)
    t0 = time.time()

    con = duckdb.connect()
    con.execute("SET memory_limit='4GB'")
    con.execute("SET threads=4")

    # ── Stage 1: D5 base — load all signals, anchor at multiple time points ───
    # Используем hours_to_resolve = 72 (3 days) как fixed anchor
    print("\n1. Loading D5 signals (hours_to_resolve=72, entry 0.70-0.95)...")
    excl = ", ".join(f"'{c}'" for c in EXCLUDE_CATS)
    df = con.execute(
        f"""
        SELECT
            m.condition_id,
            m.category,
            m.horizon_days,
            m.yes_won,
            s.yes_price
        FROM read_parquet('{MARKETS}') m
        JOIN read_parquet('{SNAPS}') s
          ON s.condition_id = m.condition_id
        WHERE s.hours_to_resolve = 72
          AND m.yes_won IS NOT NULL
          AND m.horizon_days >= 3
          AND s.yes_price >= 0.70
          AND s.yes_price < 0.95
          AND m.category NOT IN ({excl})
        """
    ).fetchdf()
    print(f"   {len(df):,} D5 signals at 72h anchor")

    df["zone"] = df["yes_price"].apply(zone)
    df["band"] = df["horizon_days"].apply(horizon_band)
    df = df.dropna(subset=["zone", "band"])

    # D5 buckets
    print("\n2. D5 per-bucket WR (NO bet)")
    print(f"{'horizon':<8} {'zone':<8} {'n':>7} {'WR':>8} {'avg_cost':>10}")
    print("-" * 50)
    d5_buckets = []
    for band in ["3-7d", "7-14d", "14d+"]:
        for z in ["high", "extreme"]:
            sub = df[(df["band"] == band) & (df["zone"] == z)]
            n = len(sub)
            if n < 50:
                continue
            wins = (sub["yes_won"] == 0).sum()
            wr = wins / n * 100
            avg_cost = (1 - sub["yes_price"]).mean()
            print(f"{band:<8} {z:<8} {n:>7,} {wr:>7.1f}% {avg_cost:>10.4f}")
            d5_buckets.append({"horizon": band, "zone": z, "n": n, "wr": wr, "avg_cost": avg_cost})

    n_d5 = len(df)
    wins = (df["yes_won"] == 0).sum()
    wr_d5 = wins / n_d5 * 100
    avg_cost = (1 - df["yes_price"]).mean()
    gross_roi = (wr_d5 / 100 - avg_cost) / avg_cost * 100
    cost_net = avg_cost + SLIPPAGE_PP / 100
    net_roi = (wr_d5 / 100 * (1 - DEFAULT_FEE_PCT * 2 / 100) - cost_net) / cost_net * 100
    days = BACKTEST_DAYS
    daily = n_d5 / days * 25 * (net_roi / 100)
    haircut = max(0.1, round(net_roi / max(gross_roi, 1), 2))

    verdict_d5 = "PASS" if (net_roi > 5 and n_d5 >= 5000) else "MARGINAL" if net_roi > 0 else "FAIL"
    write_md(
        "D5_long_horizon_extreme_fade",
        verdict_d5,
        n_d5,
        days,
        gross_roi,
        net_roi,
        wr_d5,
        daily,
        haircut,
        d5_buckets,
        "NO-fade на markets с entry_price ≥ 0.70 и horizon_days ≥ 3. Long-horizon extreme zone — retail FOMO склонен к развалам до резолва.",
        f"- **Zone:** entry [0.70, 0.95)\n- **Horizon:** ≥ 3 days\n- **Excluded:** {', '.join(EXCLUDE_CATS)}\n- **Side:** NO\n- **Anchor:** 72h",
    )

    # ── D6/D6b: D5 + bullish flow filter ────────────────────────────────────
    # maker_direction_ratio proxy = (buy_volume - sell_volume) / total_volume
    # Используем trade_buckets агрегированные за последние 24h перед anchor
    print("\n3. Loading D6 signals with maker_direction_ratio proxy...")

    df_d6 = con.execute(
        f"""
        WITH base AS (
            SELECT
                m.condition_id,
                m.category,
                m.horizon_days,
                m.end_date,
                m.yes_won,
                s.yes_price
            FROM read_parquet('{MARKETS}') m
            JOIN read_parquet('{SNAPS}') s ON s.condition_id = m.condition_id
            WHERE s.hours_to_resolve = 72
              AND m.yes_won IS NOT NULL
              AND m.horizon_days >= 3
              AND s.yes_price >= 0.70 AND s.yes_price < 0.95
              AND m.category NOT IN ({excl})
        ),
        flow AS (
            SELECT
                condition_id,
                SUM(buy_volume) AS buy_vol,
                SUM(sell_volume) AS sell_vol,
                SUM(total_volume_usd) AS total_vol
            FROM read_parquet('{TRADES}')
            GROUP BY condition_id
        )
        SELECT
            b.condition_id,
            b.category,
            b.horizon_days,
            b.yes_won,
            b.yes_price,
            CASE
                WHEN f.total_vol > 0 THEN (f.buy_vol - f.sell_vol) / f.total_vol
                ELSE 0
            END AS mdr
        FROM base b
        LEFT JOIN flow f USING (condition_id)
        """
    ).fetchdf()

    # D6 trigger: mdr > 0.20 (sustained bullish)
    d6 = df_d6[df_d6["mdr"] > 0.20].copy()
    d6["zone"] = d6["yes_price"].apply(zone)
    d6["band"] = d6["horizon_days"].apply(horizon_band)
    d6 = d6.dropna(subset=["zone", "band"])
    print(f"   D6 (mdr > 0.20): {len(d6):,} signals")

    print("\n4. D6 per-bucket WR")
    print(f"{'horizon':<8} {'zone':<8} {'n':>7} {'WR':>8}")
    print("-" * 40)
    d6_buckets = []
    for band in ["3-7d", "7-14d", "14d+"]:
        for z in ["high", "extreme"]:
            sub = d6[(d6["band"] == band) & (d6["zone"] == z)]
            n = len(sub)
            if n < 30:
                continue
            wins = (sub["yes_won"] == 0).sum()
            wr = wins / n * 100
            avg_cost = (1 - sub["yes_price"]).mean()
            print(f"{band:<8} {z:<8} {n:>7,} {wr:>7.1f}%")
            d6_buckets.append({"horizon": band, "zone": z, "n": n, "wr": wr, "avg_cost": avg_cost})

    if len(d6) >= 100:
        n_d6 = len(d6)
        wins = (d6["yes_won"] == 0).sum()
        wr_d6 = wins / n_d6 * 100
        avg_cost = (1 - d6["yes_price"]).mean()
        gross_roi_d6 = (wr_d6 / 100 - avg_cost) / avg_cost * 100
        cost_net = avg_cost + SLIPPAGE_PP / 100
        net_roi_d6 = (wr_d6 / 100 * (1 - DEFAULT_FEE_PCT * 2 / 100) - cost_net) / cost_net * 100
        daily_d6 = n_d6 / days * 25 * (net_roi_d6 / 100)

        # D6 implementation has 12h horizon → broken (canonical peak at 14d+)
        # Mark as FAIL/DEPRECATED regardless of canonical
        write_md(
            "D6_retail_bullish_overshoot",
            "FAIL",  # implementation broken
            n_d6,
            days,
            gross_roi_d6,
            net_roi_d6,
            wr_d6,
            daily_d6,
            0.0,  # implementation has 12h horizon → not tradeable
            d6_buckets,
            "D5 + maker_direction_ratio > 0.20 (sustained bullish push). Canonical peak в 14d+ extreme. Production HORIZON_SEC=12h — implementation broken.",
            "- D5 base filters\n- **Trigger:** maker_direction_ratio > 0.20\n- **HORIZON_SEC (prod):** 12h ⚠️ broken (canonical peak в 14d+)\n- **Side:** NO",
            extra="🔴 **Implementation broken:** prod HORIZON_SEC=12h vs canonical peak 14d+. Position закрывается до развала market. DEPRECATED → D6b (5-day horizon).",
        )

        # D6b — same canonical, but assume 5d horizon variant (covers 3-7d band)
        d6b = d6[d6["band"] == "3-7d"].copy()
        if len(d6b) >= 50:
            n_d6b = len(d6b)
            wins = (d6b["yes_won"] == 0).sum()
            wr_d6b = wins / n_d6b * 100
            avg_cost = (1 - d6b["yes_price"]).mean()
            gross_roi_d6b = (wr_d6b / 100 - avg_cost) / avg_cost * 100
            cost_net = avg_cost + SLIPPAGE_PP / 100
            net_roi_d6b = (wr_d6b / 100 * (1 - DEFAULT_FEE_PCT * 2 / 100) - cost_net) / cost_net * 100
            daily_d6b = n_d6b / days * 25 * (net_roi_d6b / 100)
            haircut_d6b = max(0.1, round(net_roi_d6b / max(gross_roi_d6b, 1), 2))

            verdict_d6b = "PASS" if (net_roi_d6b > 5 and n_d6b >= 500) else "MARGINAL" if net_roi_d6b > 0 else "FAIL"

            write_md(
                "D6b_long_horizon",
                verdict_d6b,
                n_d6b,
                days,
                gross_roi_d6b,
                net_roi_d6b,
                wr_d6b,
                daily_d6b,
                haircut_d6b,
                [b for b in d6_buckets if b["horizon"] == "3-7d"],
                "Same as D6, но HORIZON_SEC=5 days (compromise между broken D6 12h и canonical peak 14d+). Sweet spot 3-7d band.",
                "- D6 base + **HORIZON_SEC=5 days**\n- 3-7d band only (5d falls in middle)",
            )

    print(f"\nDone in {time.time() - t0:.1f}s")


if __name__ == "__main__":
    main()
